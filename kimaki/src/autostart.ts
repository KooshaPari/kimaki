// Start the bot when OpenCode starts. The bot writes <dataDir>/autostart.command
// on every start; the Kimaki OpenCode plugin opens it when nothing listens on
// the lock port:
//
//   kimaki start ──writes──▶ ~/.kimaki/autostart.command   (exec <bot node> <pkg>/dist/cli.js ...)
//                                       ▲
//   OpenCode loads plugin ──29988 refuses TCP──▶ open -g autostart.command
//                                                (default terminal app, in background)
//
// The script exists only after onboarding succeeded, so a fresh install never
// opens a terminal with the onboarding prompts. `kimaki --no-autostart` deletes it
// on every start instead (bots under launchd, systemd or pm2). It always runs dist/cli.js,
// also when the bot ran from src: keep dist built. --if-not-running makes a bot that
// lost the race exit instead of stopping the running one.
// Imported by the plugin (OpenCode process): no logger, no bot modules.

import { spawn } from 'node:child_process'
import fs from 'node:fs'
import net from 'node:net'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import dedent from 'string-dedent'

export const DEFAULT_LOCK_PORT = 29988

const SCRIPT_NAME = 'autostart.command'

const quote = (value: string) => `'${value.replaceAll("'", "'\\''")}'`

// <pkg>/dist/cli.js, from this file at <pkg>/{src,dist}/autostart.{ts,js}.
export function distCliEntry(): string {
  return path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'dist', 'cli.js')
}

// process.execPath is the resolved binary, for example Homebrew's
// Cellar/node/26.12.0/bin/node, which `brew upgrade node` deletes. Prefer a
// PATH entry that links to the same binary (/opt/homebrew/bin/node): it
// survives upgrades. Scripts and respawns that outlive this process use it.
export function stableNodePath(): string {
  const real = realpath(process.execPath)
  if (!real) return process.execPath
  const name = path.basename(process.execPath)
  for (const directory of (process.env['PATH'] ?? '').split(path.delimiter)) {
    if (!path.isAbsolute(directory)) continue
    const candidate = path.join(directory, name)
    if (realpath(candidate) === real) return candidate
  }
  return process.execPath
}

function realpath(file: string): string | null {
  try {
    return fs.realpathSync(file)
  } catch {
    return null
  }
}

// Windows has no autostart: it would need a .cmd script and `start`.
export async function writeAutostartScript({ dataDir, args }: { dataDir: string; args: readonly string[] }): Promise<Error | void> {
  if (process.platform === 'win32') return
  const file = path.join(dataDir, SCRIPT_NAME)
  const cli = distCliEntry()
  if (!fs.existsSync(cli)) return fs.promises.rm(file, { force: true }).catch((cause: Error) => cause)
  const command = [cli, '--if-not-running', '--data-dir', dataDir, ...args].map(quote).join(' ')
  // OpenCode is a compiled Bun binary with no Node inside, so reuse the Node that ran
  // this bot. Fall back to PATH when a version manager removed that Node.
  // The bot inherits the OpenCode (or Terminal) env: drop overrides that would change its port, token or service.
  const script = dedent`
    #!/bin/sh
    # Generated by Kimaki on bot start. The Kimaki OpenCode plugin opens it when no bot runs.
    unset KIMAKI_LOCK_PORT KIMAKI_BOT_TOKEN KIMAKI_OPENCODE_SERVICE_FILE KIMAKI_DATA_DIR KIMAKI_SUPERVISED
    node=${quote(stableNodePath())}
    [ -x "$node" ] || node=node
    echo 'Kimaki autostart'
    echo 'The agent service started and no Kimaki bot listened on port ${DEFAULT_LOCK_PORT}, so the Kimaki'
    echo 'agent plugin opened this window to start the Discord bot.'
    echo 'The bot lets you talk to your agent sessions from Discord.'
    echo 'Close this window or press Ctrl+C to stop the bot.'
    echo 'To turn autostart off, start kimaki once with --no-autostart.'
    echo "Node: $node"
    echo "Script: $0"
    echo
    exec "$node" ${command}
  ` + '\n'
  return fs.promises.writeFile(file, script, { mode: 0o755 }).then(() => fs.promises.chmod(file, 0o755))
    .catch((cause: Error) => cause)
}

export function removeAutostartScript({ dataDir }: { dataDir: string }): Promise<Error | void> {
  return fs.promises.rm(path.join(dataDir, SCRIPT_NAME), { force: true }).catch((cause: Error) => cause)
}

// True only when the connect is refused. The kernel accepts into the listen
// backlog even while the bot's event loop is busy, and a timeout (busy OpenCode
// start) is not proof of a free port: opening a window then is the bug of #243.
function lockPortIsFree(port: number): Promise<boolean> {
  return new Promise((resolve) => {
    const socket = net.connect({ host: '127.0.0.1', port })
    const done = (free: boolean) => {
      socket.destroy()
      resolve(free)
    }
    socket.setTimeout(5_000, () => done(false))
    socket.once('connect', () => done(false))
    socket.once('error', (error) => done(Reflect.get(error, 'code') === 'ECONNREFUSED'))
  })
}

// Only the default install: HOME and the default port, never KIMAKI_* env.
// Agent shells export KIMAKI_DATA_DIR, so test OpenCode servers started from
// them would otherwise start the real bot. Test servers set HOME to a temp dir.
async function startIfStopped(): Promise<void> {
  const file = path.join(os.homedir(), '.kimaki', SCRIPT_NAME)
  if (!fs.existsSync(file)) return
  // Any listener means the port is taken (V2 or V1 bot); it could not bind anyway.
  if (!(await lockPortIsFree(DEFAULT_LOCK_PORT))) return
  // macOS opens .command files in the default terminal app; -g keeps it in the background.
  const [command, args] = process.platform === 'darwin' ? ['open', ['-g', file]] as const : ['sh', [file]] as const
  const child = spawn(command, args, { detached: true, stdio: 'ignore' })
  child.on('error', () => undefined)
  child.unref()
}

// Once per OpenCode process: setup runs once per location and every reload
// re-imports the plugin, so module state would not dedupe. A bot the user
// stopped is not started again until OpenCode restarts.
const STARTED = Symbol.for('kimaki.autostart')

export function autostartBot(): void {
  if (process.platform === 'win32' || Reflect.get(globalThis, STARTED)) return
  Reflect.set(globalThis, STARTED, true)
  void startIfStopped().catch(() => undefined)
}
